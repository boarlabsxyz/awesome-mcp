// Encryption at rest against real Postgres and Redis: the rollout stages,
// a rolling deploy where code from before this feature writes the same rows,
// rotation, and the boot failures that must stop the process.
//
// Opt-in, because it RESETS the database it is given (drops schema public,
// flushes the Redis db). Point it at throwaway instances only:
//
//   docker run -d --name it-pg -e POSTGRES_PASSWORD=pw -p 55432:5432 postgres:16-alpine
//   docker run -d --name it-redis -p 56379:6379 redis:7-alpine
//   SECRETS_IT_DATABASE_URL=postgres://postgres:pw@localhost:55432/postgres \
//   SECRETS_IT_REDIS_URL=redis://localhost:56379 \
//     node --import tsx --test src/__tests__/secretsAtRest.pg.test.ts

import assert from 'node:assert/strict';
import { describe, it, before, after } from 'node:test';

const DB_URL = process.env.SECRETS_IT_DATABASE_URL;
const REDIS_URL = process.env.SECRETS_IT_REDIS_URL;
const skip = !DB_URL || !REDIS_URL
  ? 'set SECRETS_IT_DATABASE_URL and SECRETS_IT_REDIS_URL (throwaway instances: the test resets them)'
  : false;

describe('secrets at rest against Postgres and Redis', { skip }, () => {
  let db: any;
  let box: typeof import('../util/secretBox.js');
  let users: typeof import('../userStore.js');
  let conns: typeof import('../mcpConnectionStore.js');
  let catalog: typeof import('../mcpCatalogStore.js');
  let clickup: typeof import('../clickup/taskEventStore.js');
  const saved = {
    db: process.env.DATABASE_URL, redis: process.env.REDIS_URL,
    keys: process.env.TOKEN_ENCRYPTION_KEYS, seal: process.env.TOKEN_ENCRYPTION_SEAL,
  };
  const q = (sql: string, params: unknown[] = []) => db.getPool().query(sql, params);

  /** Restart "the service" with the given encryption settings. */
  async function boot(keys?: string, seal = false): Promise<void> {
    await db.closeDatabase();
    if (keys) process.env.TOKEN_ENCRYPTION_KEYS = keys; else delete process.env.TOKEN_ENCRYPTION_KEYS;
    if (seal) process.env.TOKEN_ENCRYPTION_SEAL = 'true'; else delete process.env.TOKEN_ENCRYPTION_SEAL;
    await db.initDatabase();
    assert.equal(db.isDatabaseAvailable(), true, 'booted on Postgres, not the file fallback');
  }

  const gt = { access_token: 'ya29.PLAIN', refresh_token: '1//PLAIN', scope: 's', token_type: 'Bearer', expiry_date: 1 };
  let K1: string;
  let K2: string;
  let g: any;
  let p: any;
  let c: any;

  before(async () => {
    process.env.DATABASE_URL = DB_URL;
    process.env.REDIS_URL = REDIS_URL;
    db = await import('../db.js');
    box = await import('../util/secretBox.js');
    users = await import('../userStore.js');
    conns = await import('../mcpConnectionStore.js');
    catalog = await import('../mcpCatalogStore.js');
    clickup = await import('../clickup/taskEventStore.js');
    K1 = box.generateKeyEntry('k1');
    K2 = box.generateKeyEntry('k2');

    // Reset, then the plaintext era: everything as main writes it today.
    await boot();
    await q('DROP SCHEMA public CASCADE; CREATE SCHEMA public;');
    await db.getRedis().flushdb();
    await boot();
    g = await users.createOrUpdateUser({ email: 'g@it.test', googleId: 'gid1', name: 'G' }, gt);
    p = await users.createPasswordUser({ email: 'p@it.test', name: 'P', passwordHash: 'h' });
    c = await conns.createMcpInstance(g.id, 'slack', 'S', gt, null, 'slack',
      { access_token: 'xoxp-PLAIN', accessRules: { allowedOrgs: ['T1'] } } as any);
    await catalog.createMcpCatalog({ slug: 'it', name: 'n', description: '', iconUrl: null, mcpUrl: 'u', scopes: [],
      googleClientId: 'c', googleClientSecret: 'GOCSPX-PLAIN', oauthScopes: [], isLocal: true, isActive: true });
    await clickup.createSubscription({ userId: g.id, workspaceId: 'w', clickupWebhookId: 'wh1', sharedSecret: 'SHARED-PLAIN', events: [] });
  });

  after(async () => {
    await db?.closeDatabase();
    for (const [k, v] of Object.entries({ DATABASE_URL: saved.db, REDIS_URL: saved.redis,
      TOKEN_ENCRYPTION_KEYS: saved.keys, TOKEN_ENCRYPTION_SEAL: saved.seal })) {
      if (v === undefined) delete process.env[k]; else process.env[k] = v;
    }
  });

  it('a key regenerated by older code works at once, and the revoked key stops at once', async () => {
    // Main's regenerate, run by a replica on the old code during a deploy.
    const newKey = 'f'.repeat(64);
    await q('UPDATE users SET api_key = $1, updated_at = NOW() WHERE id = $2', [newKey, p.id]);
    assert.equal(await users.getUserByApiKey(p.apiKey), undefined, 'the stale hash must not keep the old key alive');
    assert.equal((await users.getUserByApiKey(newKey))?.email, 'p@it.test');
    await boot();
    const { rows } = await q('SELECT api_key_hash FROM users WHERE id = $1', [p.id]);
    assert.equal(rows[0].api_key_hash, box.lookupHash(newKey), 'the backfill corrected the hash');
    p.apiKey = newKey;
  });

  it('step 2, keys listed without sealing: nothing is sealed and everything reads', async () => {
    await boot(K1);
    const raw = JSON.stringify((await q('SELECT google_tokens, provider_tokens FROM mcp_connections')).rows);
    assert.ok(raw.includes('xoxp-PLAIN'), 'decrypt-only must not seal');
    assert.equal((await users.getUserByApiKey(g.apiKey))?.tokens?.refresh_token, '1//PLAIN');
  });

  it('step 3, sealing on: the boot seals every stored credential, and everything still reads', async () => {
    await boot(K1, true);
    const dump = JSON.stringify([
      (await q('SELECT api_key FROM users')).rows,
      (await q('SELECT google_tokens, provider_tokens FROM mcp_connections')).rows,
      (await q('SELECT google_client_secret FROM mcp_catalog')).rows,
      (await q('SELECT shared_secret FROM clickup_webhook_subscriptions')).rows,
    ]);
    for (const s of ['ya29.PLAIN', '1//PLAIN', 'xoxp-PLAIN', 'allowedOrgs', 'GOCSPX-PLAIN', 'SHARED-PLAIN', g.apiKey, p.apiKey]) {
      assert.ok(!dump.includes(s), `left in plaintext: ${s}`);
    }
    assert.ok(box.isSealed(await db.getRedis().get('tokens:gid1')));
    assert.equal((await users.getUserByApiKey(g.apiKey))?.tokens?.refresh_token, '1//PLAIN');
    assert.equal((await users.getUserByApiKey(p.apiKey))?.email, 'p@it.test');
    const conn = await conns.getMcpConnectionByInstanceId(c.instanceId);
    assert.equal((conn?.providerTokens as any).access_token, 'xoxp-PLAIN');
    assert.equal((await catalog.getMcpCatalog('it'))?.googleClientSecret, 'GOCSPX-PLAIN');
    assert.equal((await clickup.getSubscriptionByWebhookId('wh1'))?.sharedSecret, 'SHARED-PLAIN');
  });

  it('recovers a sealed row that older code merged into in SQL, and re-seals it on the next boot', async () => {
    // Main's patchMcpInstanceProviderTokens, verbatim.
    await q(`UPDATE mcp_connections SET provider_tokens = (COALESCE(provider_tokens, '{}'::jsonb) - $3::text[]) || $1::jsonb
              WHERE instance_id = $2`, [JSON.stringify({ team: 'T9' }), c.instanceId, []]);
    let pt = (await conns.getMcpConnectionByInstanceId(c.instanceId))?.providerTokens as any;
    assert.equal(pt.access_token, 'xoxp-PLAIN', 'the token inside __enc survives');
    assert.deepEqual(pt.accessRules, { allowedOrgs: ['T1'] });
    assert.equal(pt.team, 'T9');
    await boot(K1, true);
    const { rows } = await q('SELECT provider_tokens FROM mcp_connections WHERE instance_id = $1', [c.instanceId]);
    assert.ok(box.isSealedJson(rows[0].provider_tokens), 're-sealed whole');
    pt = (await conns.getMcpConnectionByInstanceId(c.instanceId))?.providerTokens as any;
    assert.equal(pt.team, 'T9');
    assert.equal(pt.access_token, 'xoxp-PLAIN');
  });

  it('keeps concurrent provider_tokens writers from undoing each other, with compare-and-set and keepIfAbsent', async () => {
    await Promise.all(Array.from({ length: 20 }, (_, i) =>
      conns.patchMcpInstanceProviderTokens(c.instanceId, { [`k${i}`]: i })));
    let pt = (await conns.getMcpConnectionByInstanceId(c.instanceId))?.providerTokens as any;
    for (let i = 0; i < 20; i++) assert.equal(pt[`k${i}`], i, `lost k${i}`);
    assert.equal(await conns.patchMcpInstanceProviderTokens(c.instanceId, { k0: 'x' }, { expect: { k0: 999 } }), false);
    assert.equal(await conns.patchMcpInstanceProviderTokens(c.instanceId, { k0: 'x', k1: undefined }, { expect: { k0: 0, nope: undefined } }), true);
    await conns.updateMcpInstanceProviderTokens(c.instanceId, { access_token: 'xoxp-NEW' } as any, { keepIfAbsent: ['accessRules'] });
    pt = (await conns.getMcpConnectionByInstanceId(c.instanceId))?.providerTokens as any;
    assert.equal(pt.access_token, 'xoxp-NEW');
    assert.deepEqual(pt.accessRules, { allowedOrgs: ['T1'] });
    assert.ok(!('k0' in pt));
    assert.equal(await conns.patchMcpInstanceProviderTokens('missing', { a: 1 }), false);
  });

  it('rotates in stages: a key listed second seals nothing, moved first re-seals everything, then the old key can go', async () => {
    await boot(`${K1},${K2}`, true);
    let all = JSON.stringify((await q('SELECT google_tokens, provider_tokens FROM mcp_connections')).rows);
    assert.ok(!all.includes('enc1:k2:'), 'listed second: decrypt-only for k2');
    await boot(`${K2},${K1}`, true);
    all = JSON.stringify((await q('SELECT google_tokens, provider_tokens FROM mcp_connections')).rows)
      + JSON.stringify((await q('SELECT api_key FROM users')).rows);
    assert.ok(!all.includes('enc1:k1:'), 'nothing left on k1');
    assert.ok((await db.getRedis().get('tokens:gid1'))!.startsWith('enc1:k2:'));
    await boot(K2, true);
    assert.equal((await users.getUserByApiKey(g.apiKey))?.tokens?.refresh_token, '1//PLAIN');
    assert.equal((await catalog.getMcpCatalog('it'))?.googleClientSecret, 'GOCSPX-PLAIN');
  });

  it('refuses to boot on a malformed key instead of falling back to file storage', async () => {
    await db.closeDatabase();
    process.env.TOKEN_ENCRYPTION_KEYS = 'k1:c2hvcnQ=';
    process.env.TOKEN_ENCRYPTION_SEAL = 'true';
    await assert.rejects(() => db.initDatabase(), /32 bytes/);
    assert.equal(db.isDatabaseAvailable(), false);
    await boot(K2, true);
  });
});
